"""Resolves data/model paths across local, Kaggle, and Colab environments."""
import pathlib

_REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent

_DATA_DIR_CANDIDATES = [
    pathlib.Path("/kaggle/input/competitions/name-that-llm"),
    pathlib.Path("/kaggle/input/name-that-llm"),
    _REPO_ROOT / "data",
    pathlib.Path("data"),
]


def data_dir():
    for p in _DATA_DIR_CANDIDATES:
        if (p / "train.csv").exists():
            return p
    raise FileNotFoundError(
        "train.csv not found. Looked in: " + ", ".join(str(p) for p in _DATA_DIR_CANDIDATES)
    )


def models_dir():
    # /kaggle/working is the only writable dir in a Kaggle notebook; everything else is read-only.
    p = pathlib.Path("/kaggle/working/models") if pathlib.Path("/kaggle/working").exists() else _REPO_ROOT / "models"
    p.mkdir(parents=True, exist_ok=True)
    return p


_EXTERNAL_DATA_DIR_CANDIDATES = [
    pathlib.Path("/kaggle/working/data/external"),  # freshly regenerated by prepare_external_data.py on Kaggle
    pathlib.Path("/kaggle/input/name-that-llm-external-data"),  # our pre-packaged dataset, if attached
    _REPO_ROOT / "data" / "external",
    pathlib.Path("data/external"),
]


def external_data_dir():
    for p in _EXTERNAL_DATA_DIR_CANDIDATES:
        if p.exists():
            return p
    raise FileNotFoundError(
        "external data dir not found. Looked in: " + ", ".join(str(p) for p in _EXTERNAL_DATA_DIR_CANDIDATES)
    )


_EXTERNAL_POOL_CANDIDATES = [
    _REPO_ROOT / "data/external/ntl_open_pool.parquet",
    pathlib.Path("/kaggle/input/datasets/crtproduction/name-that-llm-open-pool/ntl_open_pool.parquet"),
    pathlib.Path("/kaggle/input/name-that-llm-open-pool/ntl_open_pool.parquet"),
]


def external_pool_path():
    """The big pooled-from-many-sources external dataset (226k rows, quality flags + n_sources).
    Needs its own flag-filtering/capping before use -- see train_transformer.py's
    load_external_pool() or the frozen_embeddings notebook -- unlike the smaller pre-cleaned
    prvsiyan/darragh1walsh sources external_data_dir() resolves."""
    for p in _EXTERNAL_POOL_CANDIDATES:
        if p.exists():
            return p
    raise FileNotFoundError(
        "ntl_open_pool.parquet not found. Looked in: " + ", ".join(str(p) for p in _EXTERNAL_POOL_CANDIDATES)
    )
